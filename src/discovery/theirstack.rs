//! TheirStack Jobs API adapter (decision 0012, OpenSpec change
//! `theirstack-paid-feed`): a rich, paid source. Each record carries the full
//! description (markdown) plus structured salary/remote/technology fields, so
//! the adapter maps records directly to [`IngestOutcome`] — no re-fetch of the
//! canonical page (the snapshot path).

use std::{collections::BTreeMap, future::Future, pin::Pin, sync::LazyLock};

use miette::{Context, IntoDiagnostic, Result, bail};
use regex::Regex;
use serde_json::{Value, json};
use tracing::{debug, warn};
use url::Url;

use super::{DiscoverySource, SourceBatch};
use crate::{
    config::{Config, SourceConfig},
    domain::events::{CompRange, ExtractedFields},
    ingest::{self, Fetcher, HttpClient, IngestOutcome, PoliteClient},
};

const THEIRSTACK_API: &str = "https://api.theirstack.com/v1/jobs/search";
const THEIRSTACK_BALANCE_API: &str = "https://api.theirstack.com/v0/billing/credit-balance";
/// TheirStack's maximum page size (decision 0012).
const PAGE_SIZE: u64 = 500;

pub struct Theirstack {
    api_url: String,
    api_key: String,
    posted_at_max_age_days: u64,
    strict_filtering: bool,
    blacklist: Vec<String>,
    remote_only: bool,
    compensation_floor: Option<u64>,
    discovered_at_gte: Option<String>,
    /// Operator-declared query filters (`theirstack-spend-control`
    /// decision 1), validated at construction and merged into the request
    /// body by `build_query`.
    query: BTreeMap<String, Value>,
    /// Optional per-run spend bound (`theirstack-spend-control` decision 2).
    max_credits_per_run: Option<u64>,
}

/// Query keys the adapter itself generates — unconditional reserved
/// (`theirstack-spend-control` decision 1): pagination, the recency config,
/// the watermark cursor, and the blacklist pre-filter are budgeting
/// machinery, not operator surface.
const ALWAYS_RESERVED_QUERY_KEYS: &[&str] = &[
    "limit",
    "page",
    // TheirStack's alternative pagination parameter (the deferred
    // cursor-based pagination path): a fixed operator cursor alongside the
    // adapter's `page` counter would fetch ambiguous — potentially
    // duplicate — pages, the same class of silent budgeting breakage the
    // other keys are reserved against (PR #45 review).
    "cursor",
    "posted_at_max_age_days",
    "discovered_at_gte",
    "company_name_not",
    "company_domain_not",
];
/// Query keys generated by strict mode — reserved only when
/// `strict_filtering` is on. With strict mode off they are free operator
/// surface (e.g. `workplace_types_or = ["remote", "hybrid"]`, a shape
/// strict mode cannot express).
const STRICT_RESERVED_QUERY_KEYS: &[&str] = &["workplace_types_or", "min_salary_usd"];

impl Theirstack {
    pub fn new(
        source: &SourceConfig,
        config: &Config,
        discovered_at_gte: Option<String>,
    ) -> Result<Self> {
        let query = validate_query(source)?;
        Ok(Self {
            api_url: THEIRSTACK_API.into(),
            api_key: source.api_key.clone(),
            posted_at_max_age_days: source.posted_at_max_age_days,
            strict_filtering: source.strict_filtering,
            blacklist: config.blacklist.clone(),
            remote_only: config.remote_only,
            compensation_floor: config.compensation_floor,
            discovered_at_gte,
            query,
            max_credits_per_run: source.max_credits_per_run,
        })
    }

    /// Build the search query body (pure, testable — design decisions 3 & 4):
    /// blacklist → `company_name_not`/`company_domain_not`, recency →
    /// `posted_at_max_age_days` always, and behind `strict_filtering` also
    /// `remote_only` → `workplace_types_or: ["remote"]` and `compensation_floor`
    /// → `min_salary_usd`. The operator's `[sources.theirstack.query]` table
    /// rides along after the generated keys (reserved keys were rejected at
    /// construction, so the merge cannot collide). By default the adapter
    /// adds no filters of its own beyond blacklist + recency — skills are a
    /// score dimension, not a filter, unless the operator explicitly pays to
    /// narrow the feed (`theirstack-spend-control` supersedes that default
    /// rule for an explicit query table).
    fn build_query(&self) -> Value {
        let mut query = serde_json::Map::new();
        query.insert(
            "posted_at_max_age_days".into(),
            json!(self.posted_at_max_age_days),
        );
        query.insert("limit".into(), json!(PAGE_SIZE));

        // Best-effort server-side blacklist pre-filter (the client gate is the
        // backstop): domain-looking entries → `company_domain_not`, names →
        // `company_name_not` (exact, case-sensitive).
        let mut domains = Vec::new();
        let mut names = Vec::new();
        for entry in &self.blacklist {
            if entry.contains('.') && !entry.chars().any(char::is_whitespace) {
                domains.push(Value::String(entry.clone()));
            } else {
                names.push(Value::String(entry.clone()));
            }
        }
        if !domains.is_empty() {
            query.insert("company_domain_not".into(), Value::Array(domains));
        }
        if !names.is_empty() {
            query.insert("company_name_not".into(), Value::Array(names));
        }

        if self.strict_filtering {
            if self.remote_only {
                query.insert("workplace_types_or".into(), json!(["remote"]));
            }
            if let Some(floor) = self.compensation_floor {
                query.insert("min_salary_usd".into(), json!(floor));
            }
        }

        if let Some(watermark) = &self.discovered_at_gte {
            query.insert("discovered_at_gte".into(), json!(watermark));
        }

        for (key, value) in &self.query {
            query.insert(key.clone(), value.clone());
        }

        Value::Object(query)
    }

    /// Parse a search response into jobs plus the truncation count.
    fn parse_response(value: &Value) -> Result<TheirstackResponse> {
        let data = value.get("data").and_then(Value::as_array).ok_or_else(|| {
            miette::miette!("theirstack response missing data array (shape changed?)")
        })?;
        let jobs = data.iter().map(parse_job).collect();
        let truncated_results = value
            .get("metadata")
            .and_then(|m| m.get("truncated_results"))
            .and_then(num_to_u64)
            .unwrap_or(0);
        Ok(TheirstackResponse {
            jobs,
            truncated_results,
        })
    }
}

/// One parsed TheirStack record, before mapping to [`IngestOutcome`].
#[derive(Clone, Debug)]
struct TheirstackJob {
    url: Option<String>,
    description: String,
    title: Option<String>,
    company: Option<String>,
    location: Option<String>,
    comp: Option<CompRange>,
    remote: Option<bool>,
    /// Parsed for observability and the eventual skills-scoring enrichment;
    /// the v0 skills dimension still matches resume keywords against
    /// `raw_text`, so this is not yet consumed (asserted by tests).
    #[allow(dead_code)]
    technology_slugs: Vec<String>,
    discovered_at: Option<String>,
}

#[derive(Debug)]
struct TheirstackResponse {
    jobs: Vec<TheirstackJob>,
    truncated_results: u64,
}

impl TheirstackJob {
    fn into_outcome(self) -> IngestOutcome {
        IngestOutcome {
            adapter: "theirstack".into(),
            source: "theirstack".into(),
            url: self.url,
            raw_text: self.description,
            extracted: ExtractedFields {
                title: self.title,
                company: self.company,
                location: self.location,
                remote: self.remote,
                comp: self.comp,
                ..Default::default()
            },
        }
    }
}

impl DiscoverySource for Theirstack {
    fn fetch<'a>(
        &'a self,
        client: &'a HttpClient,
    ) -> Pin<Box<dyn Future<Output = Result<SourceBatch>> + Send + 'a>> {
        Box::pin(async move {
            // A missing key fails the source (reported; run continues), never
            // a silent skip.
            if self.api_key.is_empty() {
                bail!(
                    "theirstack api_key is empty (set THEIRSTACK_API_KEY or [sources.theirstack].api_key)"
                );
            }
            let query = self.build_query();
            let api_url = Url::parse(&self.api_url).expect("static API URL parses");
            let balance_url =
                Url::parse(THEIRSTACK_BALANCE_API).expect("static balance URL parses");
            let fetched = fetch_jobs(
                client,
                &api_url,
                &query,
                &self.api_key,
                &balance_url,
                self.max_credits_per_run,
            )
            .await?;
            let discovered_at = max_discovered_at(&fetched.jobs);
            let mut outcomes = Vec::with_capacity(fetched.jobs.len());
            for job in fetched.jobs {
                emit_mismatches(&job);
                outcomes.push(job.into_outcome());
            }
            Ok(SourceBatch {
                outcomes,
                failed: 0,
                truncated_results: fetched.truncated_results,
                discovered_at,
                partial_error: fetched.partial_error,
                credits_spent: fetched.credits_spent,
            })
        })
    }

    fn charges_per_record(&self) -> bool {
        true
    }
}

/// The outcome of a paginated fetch: the jobs (possibly partial), the
/// credit-exhaustion count, the credits actually spent (records returned),
/// and — when the fetch ended early after records were already paid for —
/// why it ended (design decision 8).
#[derive(Debug, Default)]
struct FetchedJobs {
    jobs: Vec<TheirstackJob>,
    truncated_results: u64,
    credits_spent: u64,
    partial_error: Option<String>,
}

/// Validate the operator's `[sources.theirstack.query]` table
/// (`theirstack-spend-control` decision 1). Runs at adapter construction —
/// inside `build_sources` — so a bad table fails the run before any network
/// I/O and no credits are spent. Values are converted to JSON eagerly so
/// the error for an unconvertible shape (a TOML datetime) also lands here.
fn validate_query(source: &SourceConfig) -> Result<BTreeMap<String, Value>> {
    let mut out = BTreeMap::new();
    let Some(query) = &source.query else {
        return Ok(out);
    };
    for (key, value) in query {
        if ALWAYS_RESERVED_QUERY_KEYS.contains(&key.as_str()) {
            bail!(
                "[sources.theirstack.query]: '{key}' is reserved — the adapter owns \
                 pagination, recency, the watermark cursor, and the blacklist pre-filter"
            );
        }
        if source.strict_filtering && STRICT_RESERVED_QUERY_KEYS.contains(&key.as_str()) {
            bail!(
                "[sources.theirstack.query]: '{key}' collides with strict_filtering \
                 (which generates it) — remove the key or disable strict mode"
            );
        }
        let value = serde_json::to_value(value)
            .into_diagnostic()
            .wrap_err_with(|| format!("[sources.theirstack.query]: '{key}'"))?;
        out.insert(key.clone(), value);
    }
    Ok(out)
}

/// The account's remaining API credits, from the free credit-balance
/// endpoint (live shape: `{"api_credits":1700,"used_api_credits":1501,…}`).
/// One credit per record, so `remaining` is exactly how many more records
/// the account can pay for.
async fn credit_balance<F: Fetcher>(
    client: &PoliteClient<F>,
    balance_url: &Url,
    api_key: &str,
) -> Result<u64> {
    let value = client.get_json_auth(balance_url, Some(api_key)).await?;
    let total = value
        .get("api_credits")
        .and_then(num_to_u64)
        .ok_or_else(|| miette::miette!("credit balance response missing api_credits"))?;
    let used = value
        .get("used_api_credits")
        .and_then(num_to_u64)
        .unwrap_or(0);
    Ok(total.saturating_sub(used))
}

/// Why a page request failed. A payment-required (402) response is a
/// known credit-exhaustion signal at ANY page — a reported shortfall, not
/// a generic fetch failure — so it salvages even with no records fetched
/// (page 0), preserving the unreturned count as truncation (review of
/// PR #44: the old page-0 `bail!` discarded it).
#[derive(Debug)]
enum PageFailure {
    Fetch { reason: String },
    PaymentRequired { reason: String },
}

impl PageFailure {
    fn fetch(reason: String) -> Self {
        PageFailure::Fetch { reason }
    }

    fn payment_required(reason: String) -> Self {
        PageFailure::PaymentRequired { reason }
    }
}

/// Paginate the search endpoint (serial, `page`-based), bounded by the
/// credit balance and the optional per-run budget (`theirstack-spend-control`
/// decision 2). Generic over the transport seam so tests can script the
/// responses. Per page: check the balance, cap the page `limit` to what the
/// balance (and budget) can pay for, request, and stop as a partial fetch —
/// records kept, reason carried — when the balance or budget runs out. A
/// non-payment failure AFTER records have been fetched salvages them
/// (design decision 8); before any record is fetched it is a hard `Err`
/// (the whole-source failure contract). A payment-required (402) response
/// is exhaustion at ANY page and returns a partial batch (possibly empty)
/// so the unreturned count is never discarded.
#[allow(clippy::too_many_arguments)]
async fn fetch_jobs<F: Fetcher>(
    client: &PoliteClient<F>,
    api_url: &Url,
    query: &Value,
    api_key: &str,
    balance_url: &Url,
    max_credits_per_run: Option<u64>,
) -> Result<FetchedJobs> {
    let mut fetched = FetchedJobs::default();
    let mut page = 0u64;
    loop {
        // Budget pass 1 — the account balance (a free endpoint check).
        // A failed check does NOT block the fetch: warn and proceed
        // uncapped; the 402 path and the salvage are the backstop.
        let balance = match credit_balance(client, balance_url, api_key).await {
            Ok(remaining) => Some(remaining),
            Err(err) => {
                warn!(
                    error = %err,
                    "credit balance check failed; proceeding uncapped"
                );
                None
            }
        };
        let mut page_limit = PAGE_SIZE;
        if let Some(remaining) = balance {
            if remaining == 0 {
                // Nothing fetched yet: the whole-source failure contract
                // (no records, source reported failed, run continues).
                if fetched.jobs.is_empty() {
                    bail!("credit balance exhausted (0 remaining)");
                }
                // Mid-run with a drained balance: do NOT declare
                // exhaustion blindly — the result set may have ended
                // exactly at the last capped page (the false-partial bug
                // the budget-loop proptest caught: a complete fetch
                // reported as failed). Ask anyway: free either way. If
                // matches remain, the API 402s and the payment-required
                // path reports the shortfall WITH its count; if none
                // remain, the empty page completes the fetch cleanly.
                // Leave the page uncapped — the API arbitrates.
            } else {
                page_limit = page_limit.min(remaining);
            }
        }
        // Budget pass 2 — the per-run spend bound, if declared.
        if let Some(budget) = max_credits_per_run {
            let left = budget.saturating_sub(fetched.credits_spent);
            if left == 0 {
                let reason = format!(
                    "per-run credit budget of {budget} reached ({} spent)",
                    fetched.credits_spent
                );
                if fetched.jobs.is_empty() {
                    bail!("{reason}");
                }
                fetched.partial_error = Some(reason);
                return Ok(fetched);
            }
            page_limit = page_limit.min(left);
        }
        debug!(
            page,
            page_limit,
            balance = ?balance,
            spent = fetched.credits_spent,
            "theirstack page budget check"
        );

        let mut page_query = query.clone();
        if let Value::Object(ref mut map) = page_query {
            map.insert("page".into(), json!(page));
            map.insert("limit".into(), json!(page_limit));
        }
        // One page: 2xx parses; every other outcome becomes a reason
        // string. The 402 body is mined BEFORE the salvage decision — its
        // "Required: N API credits" is the unreturned-record count the
        // credit-exhaustion contract needs.
        let step: std::result::Result<TheirstackResponse, PageFailure> = match client
            .post_json_status(api_url, &page_query, Some(api_key))
            .await
        {
            Ok((status, value)) if (200..300).contains(&status) => match value {
                Some(value) => Theirstack::parse_response(&value).map_err(|e| {
                    PageFailure::fetch(format!("parsing theirstack page {page} response: {e}"))
                }),
                None => Err(PageFailure::fetch(format!(
                    "theirstack page {page}: response body is not valid JSON"
                ))),
            },
            Ok((status, value)) => {
                let mut reason = format!("fetching {api_url} failed with status {status}");
                if let Some(detail) = value
                    .as_ref()
                    .and_then(|v| v.get("error"))
                    .and_then(|e| e.get("description"))
                    .and_then(Value::as_str)
                {
                    reason.push_str(&format!(": {detail}"));
                }
                if status == 402 {
                    // The "Required: N API credits" clause is a LOWER BOUND
                    // on the unreturned tail: it is the rejected page's own
                    // requirement, min(limit, remaining matches), not the
                    // whole tail (PR #44 review). Counted before the
                    // salvage decision so it survives even a page-0 402.
                    let unreturned = unreturned_from_402(value.as_ref());
                    fetched.truncated_results += unreturned;
                    Err(PageFailure::payment_required(reason))
                } else {
                    Err(PageFailure::fetch(reason))
                }
            }
            Err(err) => Err(PageFailure::fetch(err.to_string())),
        };
        match step {
            Ok(parsed) => {
                fetched.truncated_results = fetched.truncated_results.max(parsed.truncated_results);
                let count = parsed.jobs.len() as u64;
                fetched.credits_spent += count;
                fetched.jobs.extend(parsed.jobs);
                // A short page (fewer than its own capped limit) is the end
                // of the result set. A full capped page continues — the
                // next iteration's balance/budget check decides whether
                // more is payable, and stops with a reason if not.
                if count < page_limit {
                    return Ok(fetched);
                }
                page += 1;
            }
            // Exhaustion at ANY page — including page 0 — keeps the
            // unreturned count and returns a partial batch (possibly empty):
            // the driver lists the source as failed with this reason either
            // way, and the count is never discarded.
            Err(PageFailure::PaymentRequired { reason }) => {
                fetched.partial_error = Some(reason);
                return Ok(fetched);
            }
            // A non-payment failure before any record is fetched stays a
            // hard whole-source `Err`; after records, salvage.
            Err(PageFailure::Fetch { reason }) => {
                if fetched.jobs.is_empty() {
                    bail!("{reason}");
                }
                fetched.partial_error = Some(reason);
                return Ok(fetched);
            }
        }
    }
}

/// TheirStack's 402 credit-exhaustion body states how many credits the
/// rejected page required — one credit per record, so that number is a
/// LOWER BOUND on the unreturned records (it is `min(limit, remaining
/// matches)`, the rejected page's own requirement, not the whole tail;
/// the tail would need `include_total_results`, which stays off).
/// Live-verified 2026-10-07, GWLJ-2yflze. Best-effort: any shape change
/// just yields 0, and the failure reason string still carries the full
/// error text.
fn unreturned_from_402(value: Option<&Value>) -> u64 {
    let description = value
        .and_then(|v| v.get("error"))
        .and_then(|e| e.get("description"))
        .and_then(Value::as_str)
        .unwrap_or_default();
    // Live body: "...Required: 301 API credits. You currently have 199 API
    // credits. You need 301 more API credits."
    static REQUIRED_RE: LazyLock<Regex> = LazyLock::new(|| {
        Regex::new(r"Required: (\d+) API credits").expect("static regex compiles")
    });
    REQUIRED_RE
        .captures(description)
        .and_then(|caps| caps[1].parse().ok())
        .unwrap_or(0)
}

fn parse_job(record: &Value) -> TheirstackJob {
    let description = record
        .get("description")
        .and_then(Value::as_str)
        .unwrap_or_default()
        .to_string();
    let title = record
        .get("job_title")
        .and_then(Value::as_str)
        .map(str::to_string);
    let company = record
        .get("company")
        .and_then(Value::as_str)
        .map(str::to_string)
        .or_else(|| {
            record
                .get("company_object")
                .and_then(|o| o.get("name"))
                .and_then(Value::as_str)
                .map(str::to_string)
        });
    let location = record
        .get("location")
        .and_then(Value::as_str)
        .map(str::to_string);
    let technology_slugs = record
        .get("technology_slugs")
        .and_then(Value::as_array)
        .map(|arr| {
            arr.iter()
                .filter_map(Value::as_str)
                .map(str::to_string)
                .collect()
        })
        .unwrap_or_default();

    TheirstackJob {
        url: record
            .get("final_url")
            .and_then(Value::as_str)
            .or_else(|| record.get("url").and_then(Value::as_str))
            .and_then(|u| Url::parse(u).ok())
            .map(|u| crate::domain::identity::canonicalize_url(&u)),
        description,
        title,
        company,
        location,
        comp: parse_comp(record),
        remote: parse_remote(record),
        technology_slugs,
        discovered_at: record
            .get("discovered_at")
            .and_then(Value::as_str)
            .map(str::to_string),
    }
}

/// Map TheirStack's compensation fields to a [`CompRange`]. The pipeline's
/// contract is explicit that `CompRange` is USD/year (`gates.rs`,
/// `extract.rs`), and v0 has no currency conversion — so ONLY the `_usd`
/// fields are used, with `currency: "USD"`. A posting whose only salary data
/// is in a non-USD currency (or absent) maps to `None`: unknown compensation
/// passes the permissive floor gate rather than false-rejecting a £150k
/// posting against a $180k floor (the invisible loss the permissive-gate
/// spec forbids).
fn parse_comp(record: &Value) -> Option<CompRange> {
    let min = record.get("min_annual_salary_usd").and_then(num_to_u64);
    let max = record.get("max_annual_salary_usd").and_then(num_to_u64);
    if min.is_none() && max.is_none() {
        return None;
    }
    Some(CompRange {
        min,
        max,
        currency: "USD".into(),
        period: "year".into(),
        raw: record
            .get("salary_string")
            .and_then(Value::as_str)
            .unwrap_or_default()
            .to_string(),
    })
}

fn parse_remote(record: &Value) -> Option<bool> {
    let remote = record.get("remote").and_then(Value::as_bool);
    let hybrid = record.get("hybrid").and_then(Value::as_bool);
    match (remote, hybrid) {
        (Some(true), _) => Some(true),
        (_, Some(true)) => Some(false), // hybrid is confident non-remote
        (Some(false), _) => Some(false), // explicitly not remote
        _ => None,
    }
}

/// A number field, tolerant of floats that represent whole dollars.
fn num_to_u64(value: &Value) -> Option<u64> {
    value
        .as_u64()
        .or_else(|| value.as_f64().map(|f| f.round() as u64))
}

/// One field where TheirStack's structured data disagrees with our text
/// heuristics.
#[derive(Clone, Copy, Debug, PartialEq, Eq)]
enum MismatchField {
    Comp,
    Remote,
}

/// Trust-but-verify (design decision 2): run our own text heuristics over the
/// description and compare them against TheirStack's structured fields, in
/// BOTH directions — a structured field the description contradicts, or a
/// structured field TheirStack omitted but the description quotes (the latter
/// means ingest would store "unknown" while discarding extractable data).
/// Never blocking — it exists to make TheirStack data problems visible.
fn mismatches(job: &TheirstackJob, ours: &ExtractedFields) -> Vec<MismatchField> {
    let mut out = Vec::new();
    if comp_disagrees(ours.comp.as_ref(), job.comp.as_ref()) {
        out.push(MismatchField::Comp);
    }
    if ours.remote != job.remote {
        out.push(MismatchField::Remote);
    }
    out
}

/// Whether two compensation ranges disagree on the *semantic* fields
/// (`min`, `max`, `currency`, `period`). `raw` is deliberately ignored: it is
/// a presentation string from two independent sources (our regex capture vs
/// TheirStack's `salary_string`), so it differs on almost every posting even
/// when the numbers agree — comparing it would make every comp-carrying
/// posting a phantom "mismatch" and the signal would detect nothing. A
/// `None` on one side and `Some` on the other is a real disagreement.
fn comp_disagrees(a: Option<&CompRange>, b: Option<&CompRange>) -> bool {
    match (a, b) {
        (Some(a), Some(b)) => {
            a.min != b.min || a.max != b.max || a.currency != b.currency || a.period != b.period
        }
        (None, None) => false,
        _ => true,
    }
}

/// Emit one span per mismatch carrying the structured-vs-extracted values
/// (design decision 2: `comp_structured` vs `comp_extracted`, …), keyed by
/// url and source — the lead id is not minted until ingest, and the
/// canonicalized url is the deterministic join key in Honeycomb. Never
/// blocking.
fn emit_mismatches(job: &TheirstackJob) {
    let ours = ingest::extract::extract_fields(&job.description, job.location.as_deref());
    for field in mismatches(job, &ours) {
        let span = tracing::info_span!(
            "theirstack_mismatch",
            source = "theirstack",
            url = ?job.url,
            comp_structured = tracing::field::Empty,
            comp_extracted = tracing::field::Empty,
            remote_structured = tracing::field::Empty,
            remote_extracted = tracing::field::Empty,
        );
        match field {
            MismatchField::Comp => {
                span.record("comp_structured", tracing::field::debug(&job.comp));
                span.record("comp_extracted", tracing::field::debug(&ours.comp));
                debug!(
                    parent: &span,
                    field = "comp",
                    "theirstack structured comp disagrees with text heuristics"
                );
            }
            MismatchField::Remote => {
                span.record("remote_structured", tracing::field::debug(&job.remote));
                span.record("remote_extracted", tracing::field::debug(&ours.remote));
                debug!(
                    parent: &span,
                    field = "remote",
                    "theirstack structured remote disagrees with text heuristics"
                );
            }
        }
    }
}

/// Normalize TheirStack's `discovered_at` to a canonical UTC timestamp for
/// the watermark. The API emits naive UTC stamps (second precision), but we
/// also accept explicit offsets (`Z`, `+HH:MM`, `-HH:MM`) and render
/// everything to a uniform `YYYY-MM-DDTHH:MM:SSZ`. Uniform second precision
/// is what makes the lexicographic-max in [`max_discovered_at`] correct, and
/// the cursor we send back matches the API's own stamp shape.
fn normalize_discovered_at(raw: &str) -> String {
    let raw = raw.trim();
    // Explicit offset: parse as an absolute instant and render Zulu time.
    if let Ok(ts) = raw.parse::<jiff::Timestamp>() {
        return format!("{ts:.0}");
    }
    // Naive stamp (the API's documented shape): treat as UTC.
    if let Ok(dt) = raw.parse::<jiff::civil::DateTime>()
        && let Ok(zoned) = dt.to_zoned(jiff::tz::TimeZone::UTC)
    {
        return format!("{:.0}", zoned.timestamp());
    }
    // Unknown shape: pass through unchanged rather than corrupt it.
    raw.to_string()
}

/// The max `discovered_at` across a fetch (the watermark cursor's lower
/// bound for the next run). Normalized strings are same-precision RFC 3339,
/// so lexicographic order is chronological order.
fn max_discovered_at(jobs: &[TheirstackJob]) -> Option<String> {
    jobs.iter()
        .filter_map(|j| j.discovered_at.as_deref())
        .map(normalize_discovered_at)
        .max()
}

