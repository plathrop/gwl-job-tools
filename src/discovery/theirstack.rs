    /// A captured POST: the serialized JSON body and optional bearer token.
    type CapturedRequest = (String, Option<String>);

    /// A scripted POST response: HTTP status plus the JSON body.
    type ScriptedResponse = (u16, Value);

    struct ScriptedFetcher {
        responses: Arc<Mutex<VecDeque<ScriptedResponse>>>,
        /// Scripted credit-balance GET responses, in call order (per page —
        /// the budget loop checks the balance before each page). An empty
        /// queue fails the check, exercising the warn-and-proceed-uncapped
        /// fallback.
        balance_responses: Arc<Mutex<VecDeque<ScriptedResponse>>>,
        requests: Arc<Mutex<Vec<CapturedRequest>>>,
    }

    impl ScriptedFetcher {
        /// ScriptedFetcher with no balance checks scripted (uncapped pages).
        fn new(
            responses: impl IntoIterator<Item = ScriptedResponse>,
        ) -> (Self, Arc<Mutex<Vec<CapturedRequest>>>) {
            let requests = Arc::new(Mutex::new(Vec::new()));
            (
                Self {
                    responses: Arc::new(Mutex::new(responses.into_iter().collect())),
                    balance_responses: Arc::new(Mutex::new(VecDeque::new())),
                    requests: requests.clone(),
                },
                requests,
            )
        }

        /// A live-shape balance response: total minus used = remaining.
        fn balance(total: u64, used: u64) -> ScriptedResponse {
            (
                200,
                serde_json::json!({
                    "ui_credits": 50,
                    "used_ui_credits": 0,
                    "api_credits": total,
                    "used_api_credits": used,
                    "earliest_expiration": "2026-10-25T14:40:09.456468Z"
                }),
            )
        }
    }

    impl Fetcher for ScriptedFetcher {
        async fn get(&self, _url: &Url) -> Result<FetchResponse> {
            Err(miette::miette!("get not scripted"))
        }

        async fn get_bearer(&self, _url: &Url, _bearer: Option<String>) -> Result<FetchResponse> {
            let (status, value) = self
                .balance_responses
                .lock()
                .unwrap()
                .pop_front()
                .ok_or_else(|| miette::miette!("balance response not scripted"))?;
            Ok(FetchResponse {
                status,
                retry_after: None,
                final_url: None,
                body: serde_json::to_string(&value).unwrap(),
            })
        }

        async fn post(
            &self,
            _url: &Url,
            body: String,
            bearer: Option<String>,
        ) -> Result<FetchResponse> {
            self.requests.lock().unwrap().push((body, bearer));
            let (status, value) = self
                .responses
                .lock()
                .unwrap()
                .pop_front()
                .ok_or_else(|| miette::miette!("scripted fetcher ran out of responses"))?;
            Ok(FetchResponse {
                status,
                retry_after: None,
                final_url: None,
                body: serde_json::to_string(&value).unwrap(),
            })
        }
    }

